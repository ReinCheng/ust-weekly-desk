export const lessons = lessonGroups.flatMap(group => group.lessons);
export const lessonFor = (key: string) => lessons.find(item => item.key === key);

function macroSlot(event: MarketEvent) {
  return event.category === "macro" && event.status === "confirmed" && event.impact >= 3 && event.time
    ? event.date + " " + event.time : null;
}

export function groupReleases(events: MarketEvent[]) {
  const indexed = new Map<string, MarketEvent[]>();
  for (const event of events) {
    const key = macroSlot(event) ?? event.id;
    const batch = indexed.get(key);
    if (batch) batch.push(event);
    else indexed.set(key, [event]);
  }
  return [...indexed.values()];
}

export function coReleases(event: MarketEvent, all: MarketEvent[]) {
  if (!event.time || event.status !== "confirmed") return [];
  return all.filter(other => other.id !== event.id && other.status === "confirmed" && other.impact >= 3 &&
    other.category !== "market" && other.date === event.date && other.time === event.time).sort(timeSort);
}

export function curveShape(front: number, back: number) {
  const change = Number((back - front).toFixed(2));
  if (change === 0) return "斜率持平";
  const direction = change > 0 ? "走陡" : "走平";
  if (front > 0 && back > 0) return change > 0 ? "熊陡" : "熊平";
  if (front < 0 && back < 0) return change > 0 ? "牛陡" : "牛平";
  return direction;
}
